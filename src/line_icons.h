// line_icons.h
// MVV-Liniensymbole (S-Bahn, U-Bahn, Tram, Nacht-Tram) als 1-Bit-XBM, 16 px hoch.
// Quelle S/U: Wikimedia Commons (Dateien "Muenchen_S1.svg", "Muenchen_U1.svg"
// usw., dort als gemeinfrei / Public Domain gekennzeichnet), auf 16 px Hoehe
// in 1-Bit konvertiert. Die Liniensymbole koennen Marken der jeweiligen
// Inhaber (MVV, MVG, DB) sein.
// Tram + Nacht-Tram: einheitlich 30x16, schwarzer Kasten, weisse Pixel-Ziffern
// (eigene 6x10-Pixelschrift, N 7x10).
// S-Bahn einheitlich 36x16 (S5 auf 36 px angeglichen).
// WICHTIG: NACH <heltec-eink-modules.h> einbinden (BLACK/WHITE werden benoetigt).
//
// Format: XBM (LSB zuerst), direkt nutzbar mit Adafruit-GFX drawXBitmap():
//   const LineIcon* ic = findLineIcon(departures[i].line);
//   if (ic) display.drawXBitmap(x, yTop, ic->bits, ic->width, LINE_ICON_HEIGHT, BLACK);
//
// Schluessel = "label" aus der MVG-API: "S1", "U3", Tram nur Nummer ("19"),
// Nacht-Tram "N17". Busse haben kein Icon -> drawLineIcon() erzeugt dafuer
// zur Laufzeit einen Rahmen mit der Liniennummer (siehe unten).
// Flash-Bedarf aller Bitmaps: ca. 2960 Bytes.

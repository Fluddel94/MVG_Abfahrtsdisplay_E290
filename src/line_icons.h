static const uint8_t BUS_GLYPH_COUNT = sizeof(BUS_GLYPHS) / sizeof(BUS_GLYPHS[0]);

inline const BusGlyph* findBusGlyph(char ch) {
  for (uint8_t i = 0; i < BUS_GLYPH_COUNT; i++) {
    if (BUS_GLYPHS[i].ch == ch) return &BUS_GLYPHS[i];
  }
  return nullptr;
}

// Breite eines Labels in der Pixelschrift, -1 wenn ein Zeichen fehlt
inline int busTextWidth(const String& label) {
  int w = 0;
  for (unsigned int i = 0; i < label.length(); i++) {
    const BusGlyph* g = findBusGlyph(label[i]);
    if (g == nullptr) return -1;
    w += g->width;
    if (i > 0) w += BUS_GLYPH_GAP;
  }
  return w;
}

// Zeichnet ein Bus-Icon (Rahmen + Nummer) mit Oberkante bei yTop und gibt
// die Breite zurueck. Rahmen 2 px, bei langen Nummern 1 px, Breite zwischen
// BUS_ICON_MIN_WIDTH und LINE_ICON_MAX_WIDTH. Enthaelt das Label Zeichen
// ohne Glyphe oder ist es zu lang, wird die eingebaute 6x8-Schrift von
// Adafruit-GFX verwendet (ggf. gekuerzt). ACHTUNG: Der Fallback setzt die
// Schrift zurueck - Aufrufer muss danach seine Schrift neu setzen.
template <typename GFX>
int drawBusIcon(GFX& d, int x, int yTop, const String& label) {
  int textW = busTextWidth(label);
  int border = 2;
  int pad = 2;
  if (textW >= 0 && textW + 2 * (border + pad) > LINE_ICON_MAX_WIDTH) {
    border = 1;
    pad = 1;
  }

  if (textW >= 0 && textW + 2 * (border + pad) <= LINE_ICON_MAX_WIDTH) {
    int w = textW + 2 * (border + pad);
    if (w < BUS_ICON_MIN_WIDTH) w = BUS_ICON_MIN_WIDTH;

    for (int i = 0; i < border; i++) {
      d.drawRect(x + i, yTop + i, w - 2 * i, LINE_ICON_HEIGHT - 2 * i, BLACK);
    }

    int cx = x + (w - textW) / 2;
    for (unsigned int i = 0; i < label.length(); i++) {
      const BusGlyph* g = findBusGlyph(label[i]);
      for (int r = 0; r < BUS_GLYPH_HEIGHT; r++) {
        for (int c = 0; c < g->width; c++) {
          if (g->rows[r] & (1 << c)) {
            d.drawPixel(cx + c, yTop + BUS_GLYPH_TOP + r, BLACK);
          }
        }
      }
      cx += g->width + BUS_GLYPH_GAP;
    }
    return w;
  }

  // Fallback: eingebaute GFX-Schrift (6 px pro Zeichen inkl. Abstand, 8 px hoch)
  const int maxChars = (LINE_ICON_MAX_WIDTH - 4) / 6;
  String text = label;
  if ((int)text.length() > maxChars) text = text.substring(0, maxChars);
  int w = text.length() * 6 + 3;
  if (w < BUS_ICON_MIN_WIDTH) w = BUS_ICON_MIN_WIDTH;
  d.drawRect(x, yTop, w, LINE_ICON_HEIGHT, BLACK);
  d.setFont(NULL);
  d.setTextSize(1);
  d.setTextColor(BLACK);
  d.setCursor(x + (w - (int)text.length() * 6 + 1) / 2, yTop + 4);
  d.print(text);
  return w;
}

// Zeichnet das passende Liniensymbol mit Oberkante bei yTop und gibt die
// Breite zurueck (max. LINE_ICON_MAX_WIDTH):
// - isBus = true (laut API ein Bus): immer generiertes Bus-Icon, auch wenn
//   es eine Tram mit gleicher Nummer gibt
// - sonst: Bitmap aus LINE_ICONS, falls vorhanden
// - unbekannte Linien (z.B. Regionalzuege "RB56"): ebenfalls Rahmen mit Text
// Funktioniert mit jedem Adafruit-GFX-kompatiblen Display-Objekt.
template <typename GFX>
int drawLineIcon(GFX& d, int x, int yTop, const String& label, bool isBus) {
  if (!isBus) {
    const LineIcon* ic = findLineIcon(label);
    if (ic) {
      d.drawXBitmap(x, yTop, ic->bits, ic->width, LINE_ICON_HEIGHT, BLACK);
      return ic->width;
    }
  }
  return drawBusIcon(d, x, yTop, label);
}
